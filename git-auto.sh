#!/bin/bash
# Workflow git rapide pour utoutlook (évite d'appeler l'IA pour les commits/push)
set -e

if [ "$1" = "--help" ] || [ "$1" = "-h" ] || [ -z "$1" ]; then
  echo "Usage: ./git-auto.sh <commande> [args]"
  echo ""
  echo '  status                        -> branche courante, commits en avance, fichiers modifies'
  echo '  commit "fix(vX.Y.Z): desc"    -> git add -A + commit avec pied Vibe + grep brethous'
  echo '  push                          -> push la branche (hook pre-push bloque les .click)'
  echo '  pr "Titre de la PR"           -> push + cree la PR (gh si installe, sinon URL GitHub)'
  echo '  livraison <version> "titre"    -> assemble livraison/utoutlook-<version>/ de CE dépôt (click + CHANGELOG + README), commit (git add -f)'
  echo '  newfix <nom>                  -> cree fix/<nom> depuis main a jour'
  exit 0
fi

CMD="${1:?Usage: $0 commit|push|pr|newfix|status ...}"
ROOT="$(cd "$(dirname "$0")" && pwd)"
APP_PREFIX="utoutlook"
APP_ID="utoutlook.mathias"
cd "$ROOT"

FOOTER=$'Built and tested by Mathias — code written by Vibe, reviewed and controlled by Mathias.\nGenerated by Mistral Vibe & control by Mathias.\nAssisted by DeepSeek V4.1 Flash Free (OpenCode) — reviewed and controlled by Mathias.\nCo-Authored-By: Mistral Vibe <vibe@mistral.ai> and Mathias'

case "$CMD" in
  commit)
    MSG="${2:?message requis}"
    git add -A
    # Garde-fou confidentialité (règle Mathias 2026-11-01)
    if grep -ri brethous --exclude-dir=.git --exclude-dir=node_modules --exclude-dir=build --exclude-dir=dist --exclude=AGENTS.md --exclude=check.sh --exclude=git-auto.sh --exclude=menu.sh . 2>/dev/null | grep -q .; then
      echo "ERREUR: 'brethous' détecté dans le working tree — commit annulé (règle confidentialité)"
      exit 1
    fi
    git commit -m "$MSG

$FOOTER"
    echo "OK: $(git log --oneline -1)"
    ;;

  push)
    BR=$(git branch --show-current)
    echo "Push de la branche '$BR'..."
    git push -u origin "$BR" 2>&1 | tail -5
    echo "(le hook pre-push bloque automatiquement tout .click)"
    ;;

  pr)
    TITLE="${2:?titre de la PR requis}"
    BR=$(git branch --show-current)
    git push -u origin "$BR" 2>&1 | tail -3
    if command -v gh >/dev/null 2>&1; then
      gh pr create --title "$TITLE" --body "$(git log main..HEAD --oneline)" 2>&1 | tail -3
    else
      echo "gh non installé — crée la PR manuellement :"
      echo "  https://github.com/mathiasmb31/utoutlook/compare/$BR?expand=1"
    fi
    ;;

  newfix)
    NAME="${2:?nom du fix requis}"
    git checkout main
    git pull --ff-only origin main 2>/dev/null || true
    git checkout -b "fix/$NAME"
    echo "Branche fix/$NAME créée depuis main"
    ;;

  livraison)
    VER="${2:?version requise (ex: 4.0.61)}"
    TITRE="${3:-livraison $APP_PREFIX $VER}"
    # Règle Mathias : la livraison vit dans CE dépôt (livraison/utoutlook-<ver>/),
    # pas dans ../livraison (ancienne convention du workspace).
    LIV="$ROOT/livraison/$APP_PREFIX-$VER"
    mkdir -p "$LIV"

    # Le .click est produit par clickable dans utoulookmail/build/<arch>/app/.
    CLICK=""
    for c in "$ROOT"/utoulookmail/build/*/app/"${APP_ID}_${VER}_arm64.click" \
             "$ROOT"/livraison/*/"${APP_ID}_${VER}_arm64.click"; do
      [ -f "$c" ] && CLICK="$c" && break
    done
    if [ -z "$CLICK" ]; then
      # Pas de repli sur un .click d'une autre version : une livraison doit
      # contenir le click de SA version (build reproductible).
      LATEST="$(find "$ROOT/utoulookmail/build" -name '*.click' 2>/dev/null | sort -V | tail -1)"
      echo "ERREUR: aucun .click pour ${VER} dans utoulookmail/build/*/app/ — build manuel d'abord (./build-deploy.sh ${VER})"
      [ -n "$LATEST" ] && echo "  (dernier .click construit : $(basename "$LATEST"))"
      exit 1
    else
      cp -f "$CLICK" "$LIV/"
      echo "click copié: $(basename "$CLICK")"
    fi

    # Version synchronisée dans manifest.json + package.json (règle avant build)
    PKG_VER=$(grep -m1 '"version"' "$ROOT/utoulookmail/utoutlookmail/package.json" 2>/dev/null | sed 's/.*"version"[[:space:]]*:[[:space:]]*"//;s/".*//')
    if [ "$PKG_VER" != "$VER" ]; then
      echo "ATTENTION: package.json=$PKG_VER ≠ $VER — ./bump-version.sh $VER puis rebuild"
    fi

    # CHANGELOG.md + README.txt obligatoires (règle livraison)
    MISSING=0
    for f in CHANGELOG.md README.txt; do
      [ -f "$LIV/$f" ] || { echo "MANQUANT: $LIV/$f"; MISSING=1; }
    done
    if [ "$MISSING" -eq 1 ]; then
      echo "Livraison annulée : rédige CHANGELOG.md + README.txt dans $LIV puis relance."
      exit 1
    fi
    for f in CHANGELOG.md README.txt; do
      grep -qi 'Built and tested by Mathias' "$LIV/$f" ||
        echo "ATTENTION: ligne de crédit « Built and tested by Mathias — code written by Vibe… » absente de $f"
    done

    cd "$ROOT"
    git add livraison/
    for c in "$LIV"/*.click; do [ -f "$c" ] && git add -f "$c"; done
    git commit -m "$TITRE

$FOOTER"
    echo "OK: $(git log --oneline -1)"
    echo "Reste: push filtré (le hook pre-push bloque les .click) puis PR:"
    echo "  cd $ROOT && git push origin $(git branch --show-current)"
    echo "  (si le hook bloque à cause du .click : base-de-connaissances/restauration-workspace-vibe-2026-11-06.md, push filtré)"
    ;;

  status)
    echo "Branche: $(git branch --show-current)"
    echo "Commits en avance sur origin/main: $(git rev-list --count origin/main..HEAD 2>/dev/null || echo '?')"
    echo "Fichiers modifiés non commités:"
    git status --short | head -10
    ;;

  *)
    echo "Commandes: commit|push|pr|newfix|status"
    exit 1
    ;;
esac
